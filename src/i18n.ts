type MessageSchema = typeof messages['zh-CN']
export type MessageKey = keyof MessageSchema

export const setLocale = (nextLocale: AppLocale) => {
  locale.value = nextLocale
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem(LOCALE_STORAGE_KEY, nextLocale)
  }
  applyDocumentLocale(nextLocale)
}

export const t = (key: MessageKey, ...args: unknown[]) => {
  const value = messages[locale.value][key] as MessageSchema[typeof key]
  return typeof value === 'function' ? (value as (...params: unknown[]) => string)(...args) : value
}
