import { ref } from 'vue'

const LOCALE_STORAGE_KEY = 'tersterm.locale'

export const supportedLocales = ['zh-CN', 'en-US'] as const

export type AppLocale = (typeof supportedLocales)[number]

const DEFAULT_LOCALE: AppLocale = 'zh-CN'

const isAppLocale = (value: string | null): value is AppLocale =>
  Boolean(value && supportedLocales.includes(value as AppLocale))

const readStoredLocale = (): AppLocale => {
  if (typeof localStorage === 'undefined') return DEFAULT_LOCALE

  const storedLocale = localStorage.getItem(LOCALE_STORAGE_KEY)
  return isAppLocale(storedLocale) ? storedLocale : DEFAULT_LOCALE
}

const applyDocumentLocale = (nextLocale: AppLocale) => {
  if (typeof document === 'undefined') return

  document.documentElement.lang = nextLocale === 'zh-CN' ? 'zh-CN' : 'en'
}

export const locale = ref<AppLocale>(readStoredLocale())

applyDocumentLocale(locale.value)

